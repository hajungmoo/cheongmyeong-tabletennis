export function safeURL(value, fallback = '') {
  const s = String(value || '').trim();
  if (!s) return fallback;
  if (/^(?:https:\/\/|\/(?!\/)|\.?\.?\/|#)/i.test(s) || (!s.includes(':') && !s.startsWith('\\') && /^[a-zA-Z0-9가-힣_%-][^<>"\\]*$/.test(s))) return s;
  return fallback;
}
export function validISO(value) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(value || '')) return '';
  const d = new Date(value+'T12:00:00Z');
  return Number.isFinite(d.getTime()) && d.toISOString().slice(0,10) === value ? value : '';
}
export function scheduleDate(item) {
  if (validISO(item.startDate)) return item.startDate;
  const text = String(item.date || item.day || '');
  const m = text.match(/^(\d{4})[.\-/]\s*(\d{1,2})[.\-/]\s*(\d{1,2})/);
  return m ? validISO(`${m[1]}-${m[2].padStart(2,'0')}-${m[3].padStart(2,'0')}`) : '';
}
export function koreaToday() {
  return new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Seoul',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date());
}
export function scheduleState(item, today = koreaToday()) {
  const start = scheduleDate(item), end = validISO(item.endDate) || start;
  return !start ? 'other' : end < today ? 'past' : start <= today ? 'ongoing' : 'upcoming';
}
