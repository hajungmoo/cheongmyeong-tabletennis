const normalizedName=value=>String(value||'').normalize('NFKC').replace(/\s+/g,'').toLocaleLowerCase('ko-KR');
const normalizedSchool=value=>String(value||'').normalize('NFKC').replace(/\s+/g,'').replace(/초등학교$/,'초').replace(/중학교$/,'중').replace(/[().·-]/g,'').toLowerCase();
const unique=values=>[...new Set(values.filter(Boolean))];
function schoolNames(spec){return unique([spec.name,...spec.aliases,...spec.aliases.filter(name=>/초$/.test(name)).map(name=>name.slice(0,-1))]);}
function matchingSchools(db,spec){
  const names=new Set(schoolNames(spec).map(normalizedSchool));
  return db.schools.filter(school=>[school.name,...(school.aliases||[])].some(name=>names.has(normalizedSchool(name))));
}
function stableId(prefix,key,records){
  const base=prefix+Array.from(key).reduce((hash,character)=>(hash*33+character.charCodeAt(0))>>>0,5381).toString(36);
  let id=base,index=2;while(records.some(record=>record.id===id))id=base+'_'+index++;return id;
}
export function applyRoster(db){
  if(!db||!Array.isArray(db.players)||!Array.isArray(db.schools))throw new Error('INVALID_ROSTER_DATABASE');
  if(db.migrations?.[MIGRATION])return {changed:false,report:db.migrations[MIGRATION]};
  const report={source:SOURCE,appliedOn:'2026-10-08',catalogSize:ROSTER.length,matchedPlayers:0,addedPlayers:0,addedSchools:0,updatedSchoolNames:0,adds:[]};
  const schools=new Map();
  for(const spec of SCHOOL_SPECS){
    const candidates=matchingSchools(db,spec);
    let target=candidates.find(school=>normalizedSchool(school.name)===normalizedSchool(spec.name))||candidates[0];
    if(!target){target={id:stableId('s_bracket_',spec.name,db.schools),name:spec.name,ours:false,aliases:[]};db.schools.push(target);candidates.push(target);report.addedSchools++;}
    const schoolSuffix=spec.name.endsWith('중학교')?'중학교':spec.name.endsWith('초등학교')?'초등학교':null;
    if(schoolSuffix&&!target.name.endsWith(schoolSuffix)){target.aliases=unique([target.name,...(target.aliases||[])]);target.name=spec.name;report.updatedSchoolNames++;}
    target.aliases=unique([...(target.aliases||[]),...schoolNames(spec)]);
    schools.set(spec.name,{target,ids:new Set(candidates.map(school=>school.id))});
  }
  for(const record of ROSTER){
    const school=schools.get(record.school),names=new Set([record.name,...record.aliases].map(normalizedName));
    const existing=db.players.some(player=>(!player.gender||player.gender===record.gender)&&school.ids.has(player.schoolId)&&[player.name,...(player.aliases||[])].some(name=>names.has(normalizedName(name))));
    if(existing){report.matchedPlayers++;continue;}
    const player={id:stableId('p_bracket_',record.gender+'|'+record.school+'|'+record.name,db.players),name:record.name,gender:record.gender,grade:'',schoolId:school.target.id,overallRank:null,gradeRank:null,rankPoints:null,aliases:[...record.aliases],transferHistory:[],rankHistory:[],status:'재학',current:true,source:MIGRATION,divisionGroups:[...record.divisions],createdAt:new Date().toISOString()};
    db.players.push(player);report.addedPlayers++;report.adds.push({name:player.name,school:school.target.name,divisions:[...record.divisions]});
  }
  db.migrations=db.migrations||{};db.migrations[MIGRATION]=report;
  return {changed:true,report};
}
// Read the current server document inside a transaction. Never upload a stale local snapshot.
export async function migrateRoster({auth,fs,ref,runTransaction,decodePayload,gzipEncode,serverTimestamp}){
  if(!auth.currentUser)return null;
  const uid=auth.currentUser.uid;
  return runTransaction(fs,async transaction=>{
    const snapshot=await transaction.get(ref);
    if(!snapshot.exists())return null;
    const raw=snapshot.data(),db=await decodePayload(raw.encoding,raw.payload),result=applyRoster(db);
    if(!result.changed)return null;
    const encoded=await gzipEncode(db);
    if(auth.currentUser?.uid!==uid)throw new Error('ROSTER_LOGIN_CHANGED');
    const revision=Math.max(Date.now(),Number(raw.revision||0)+1);
    transaction.set(ref,{...raw,...encoded,revision,updatedAt:serverTimestamp(),summary:{matches:(db.matches||[]).length,players:db.players.length,schools:db.schools.length,leagues:(db.leagues||[]).length,competitions:(db.competitions||[]).length}});
    return result.report;
  });
}
